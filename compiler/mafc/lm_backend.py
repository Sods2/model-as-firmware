"""MafLM back end (v1): integer model (.npz from train/lm/intref.py --npz) -> C data for the RP2350 LM runtime.

Writes gen/maflm_<name>.h (LM_* constants) and gen/maflm_<name>.c (packed ternary weights, int8 embedding,
multipliers, and the lm_model descriptor read by firmware/rp2350/maflm/lm_rt.c), plus gen/lm_exp2.inc.

Ternary packing: one byte per 4 trits, as a base-3 number (pack_trits). Layers whose rows are a
multiple of 4 (all but the tree nodes) interleave groups of 4 rows byte by byte (lm_rt.h, il = 1); every packed array
is decoded again and compared before it is written.
"""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np

EXP2 = [round(2 ** 15 * 2 ** (i / 256)) for i in range(256)]


def load_npz(path: Path) -> dict:
    z = np.load(path)
    im = {"config": {}}
    for k in z.files:
        v = z[k]
        if k.startswith("cfg."):
            im["config"][k[4:]] = int(v)
        else:
            im[k] = v.item() if v.ndim == 0 else v
    im["config"]["ffn"] = "tree" if im["config"]["ffn"] else "dense"
    return im


def interleave4(packed: np.ndarray, rows: int, cols: int) -> np.ndarray:
    """Row-major packed bytes -> groups of 4 rows interleaved byte by byte (see lm_rt.h, il = 1)."""
    assert rows % 4 == 0
    cb = cols // 4
    return packed.reshape(rows // 4, 4, cb).transpose(0, 2, 1).reshape(-1).copy()


def pack_trits(w: np.ndarray) -> np.ndarray:
    """One byte per 4 trits: the base-3 number d0 + 3 d1 + 9 d2 + 27 d3 (digit 0 = 0, 1 = +1, 2 = -1), row-major.
    The runtime indexes an 81-entry table of activation partial sums with it (lm_rt.c, build_tab)."""
    rows, cols = w.shape
    assert cols % 4 == 0 and set(np.unique(w)) <= {-1, 0, 1}
    d = np.where(w == 1, 1, np.where(w == -1, 2, 0)).astype(np.int64).reshape(rows, cols // 4, 4)
    packed = (d[..., 0] + 3 * d[..., 1] + 9 * d[..., 2] + 27 * d[..., 3]).astype(np.uint8)
    dec = np.zeros((rows, cols // 4, 4), np.int64)                         # round trip
    v = packed.astype(np.int64)
    for k in range(4):
        dk = (v // 3 ** k) % 3
        dec[..., k] = np.where(dk == 1, 1, np.where(dk == 2, -1, 0))
    assert np.array_equal(dec.reshape(rows, cols), w), "trit packing round trip failed"
    return packed.reshape(-1)


def c_array(ctype: str, name: str, data, per_line: int = 32, attrs: str = "") -> str:
    vals = [str(int(v)) for v in np.asarray(data).reshape(-1)]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return f"static const {ctype} {name}[{len(vals)}]{attrs} = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def generate(im: dict, name: str, out_dir: Path, window: int = 256) -> dict:
    c = im["config"]
    tree = c["ffn"] == "tree"
    out_dir.mkdir(parents=True, exist_ok=True)
    leaf = c["hidden"] // (2 ** c["depth"])
    shifts = [int(s) for s in np.asarray(im["alibi_shift"]).reshape(-1)]

    hdr = [f"// Generated by compiler/compile_lm.py from {name}.npz. Do not edit.",
           "#pragma once",
           f'#define LM_MODEL_NAME "{name}"',
           f"#define LM_VOCAB {c['vocab']}", f"#define LM_D {c['d']}", f"#define LM_LAYERS {c['layers']}",
           f"#define LM_HEADS {c['heads']}", f"#define LM_KV_HEADS {c['kv_heads']}", f"#define LM_D_HEAD {c['d_head']}",
           f"#define LM_HIDDEN {c['hidden']}", f"#define LM_TREE {int(tree)}", f"#define LM_DEPTH {c['depth']}",
           f"#define LM_LEAF {leaf}", f"#define LM_WINDOW {window}", f"#define LM_F {int(im['F'])}",
           f"#define LM_KQ {int(im['KQ'])}LL",
           "#define LM_ALIBI_SHIFTS {" + ", ".join(map(str, shifts)) + "}"]
    (out_dir / f"maflm_{name}.h").write_text("\n".join(hdr) + "\n")
    (out_dir / "lm_exp2.inc").write_text(",\n".join(", ".join(map(str, EXP2[i:i + 16])) for i in range(0, 256, 16)) + "\n")

    body = [f"// Generated by compiler/compile_lm.py from {name}.npz. Do not edit.",
            '#include "lm_rt.h"', ""]
    stats = {"packed_bytes": 0}

    def lin(key: str, cname: str, il: bool = True) -> str:
        w = im[key + ".codes"]
        p = pack_trits(w)
        il = il and w.shape[0] % 4 == 0
        if il:
            p = interleave4(p, *w.shape)
        stats["packed_bytes"] += p.size
        body.append(c_array("uint8_t", cname, p, attrs=" __attribute__((aligned(4)))"))
        return f"{{ {cname}, {w.shape[0]}, {w.shape[1]}, {int(im[key + '.wmul'])}, {int(il)} }}"

    blocks = []
    for i in range(c["layers"]):
        f = {nm: lin(f"b{i}.{nm}", f"b{i}_{nm}") for nm in ("wq", "wk", "wv", "wo")}
        if tree:
            f["nodes"] = lin(f"b{i}.nodes", f"b{i}_nodes", il=False)   # read one row at a time
            f["leaf_in"] = lin(f"b{i}.leaf_in", f"b{i}_leaf_in")
            lo = [lin(f"b{i}.leaf_out{j}", f"b{i}_leaf_out{j}") for j in range(2 ** c["depth"])]
            ffn = f".nodes = {f['nodes']}, .leaf_in = {f['leaf_in']}, .leaf_out = {{ {', '.join(lo)} }}"
        else:
            ffn = f".w1 = {lin(f'b{i}.w1', f'b{i}_w1')}, .w2 = {lin(f'b{i}.w2', f'b{i}_w2')}"
        blocks.append(f"    {{ .wq = {f['wq']}, .wk = {f['wk']}, .wv = {f['wv']}, .wo = {f['wo']}, {ffn} }}")
    un = lin("unembed", "unembed")
    body.append(c_array("int8_t", "embed_codes", im["embed.codes"]))
    body.append(c_array("int32_t", "embed_mul", im["embed.mul"]))
    stats["embed_bytes"] = im["embed.codes"].size + 4 * im["embed.mul"].size
    body.append("const lm_model_t lm_model = {\n    .embed_codes = embed_codes, .embed_mul = embed_mul,\n"
                "    .blocks = {\n" + ",\n".join(blocks) + "\n    },\n    .unembed = " + un + "\n};\n")
    (out_dir / f"maflm_{name}.c").write_text("\n".join(body))
    kv = c["layers"] * window * (2 * c["kv_heads"] * c["d_head"] + 8 * c["kv_heads"])
    stats["kv_bytes"] = kv
    return stats
