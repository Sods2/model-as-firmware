"""Write the CMSIS-NN header for the s4 variant: same model, fc1 weights packed as CMSIS-NN s4.

    python harness/export_cmsis_s4.py --model tern80

Reads firmware/baselines/cmsis_nn/model_s8_<model>.h (written by export_cmsis.py) and writes model_s4fc1_<model>.h
next to it: everything copied unchanged, except that s8_fc1_w is replaced by s4_fc1_w, packed two weights per byte,
first weight in the low nibble (the format arm_fully_connected_s4 documents: [0x1, 0x2, 0x3, 0x4] -> [0x21, 0x43]). fc1 is ternary, so its weights are the same integers and the s4 build must give exactly the same logits
as the s8 build; it is checked against the same golden model (GoldenS8).

Only fc1: fc2/fc3 are BitNetMCU '4bitsym' weights with the odd levels +-1, +-3, ..., +-15 (weight = +-(2m+1)), which
don't fit a two's-complement int4 (-8..7). Running them as s4 would mean re-quantizing them, a different model. The
script refuses any array that doesn't fit, so it checks this rather than assuming it.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIR = ROOT / "firmware" / "baselines" / "cmsis_nn"
ARR = re.compile(r"const int8_t (s8_fc1_w)\[\] = \{(.*?)\};", re.S)


def pack(vals: list[int]) -> list[int]:
    if len(vals) % 2:
        vals = vals + [0]
    out = []
    for lo, hi in zip(vals[0::2], vals[1::2]):
        b = (lo & 0x0F) | ((hi & 0x0F) << 4)
        out.append(b - 256 if b > 127 else b)
    return out


def unpack(packed: list[int], n: int) -> list[int]:
    v = []
    for b in packed:
        b &= 0xFF
        for nib in (b & 0x0F, b >> 4):
            v.append(nib - 16 if nib > 7 else nib)
    return v[:n]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="tern80")
    a = ap.parse_args()
    src = DIR / f"model_s8_{a.model}.h"
    text = src.read_text()
    found = []

    def repl(m: re.Match) -> str:
        name = m.group(1)
        vals = [int(x) for x in m.group(2).replace("\n", " ").split(",") if x.strip()]
        lo, hi = min(vals), max(vals)
        if lo < -8 or hi > 7:
            raise SystemExit(f"{name}: values {lo}..{hi} don't fit in int4")
        p = pack(vals)
        assert unpack(p, len(vals)) == vals
        found.append(f"{name}: {len(vals)} weights in [{lo}, {hi}] -> {len(p)} bytes")
        rows = [", ".join(str(x) for x in p[i:i + 24]) for i in range(0, len(p), 24)]
        new = name.replace("s8_", "s4_")
        return f"const int8_t {new}[] = {{  // {len(vals)} int4 weights, packed (low nibble first)\n    " + \
               ",\n    ".join(rows) + "\n};"

    out = ARR.sub(repl, text)
    if len(found) != 1:
        raise SystemExit(f"expected the fc1 array, found {len(found)}")
    out = out.replace("MODEL_S8_H", "MODEL_S4FC1_H")
    out = f"// Generated by harness/export_cmsis_s4.py from {src.name}: fc1 packed as CMSIS-NN s4.\n" + out
    dst = DIR / f"model_s4fc1_{a.model}.h"
    dst.write_text(out)
    print("\n".join(found))
    print(f"wrote {dst}")


if __name__ == "__main__":
    main()
