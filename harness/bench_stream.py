"""Idea C benchmark (FINDINGS F21): stream weights from flash with DMA while computing, against reading them
in place through the XIP cache. One dense int8 linear layer, 256 -> 256 (64 KB of weights, 4x the 16 KB cache).

  gen:  write firmware/bench/stream/gen/stream_data.h (weights, input, expected output checksum)
  run:  drive the flashed benchmark firmware over USB serial and append rows to results/bench_stream.csv

  python harness/bench_stream.py gen
  (build + flash firmware/bench/stream, flash build: the weights must stay in flash)
  python harness/bench_stream.py run --port COM3
"""
import argparse
import csv
import datetime
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / 'firmware' / 'bench' / 'stream' / 'gen'
N_IN = N_OUT = 256
SEED = 4321


def checksum(out):
    o = np.asarray(out, dtype=np.int64).reshape(-1) & 0xFFFFFFFF
    k = np.arange(o.size) + 1
    return int((o * k).sum() & 0xFFFFFFFF)


def gen():
    rng = np.random.default_rng(SEED)
    w = rng.integers(-128, 128, size=(N_OUT, N_IN), dtype=np.int64)
    a = rng.integers(0, 128, size=N_IN, dtype=np.int64)
    out = w @ a
    chk = checksum(out)
    # weights as stored: per row, groups of 4 in byte order w0 w2 w1 w3, so that SXTB16(word) = (w0, w1)
    # and SXTB16(word ror 8) = (w2, w3) line up with the int16 input pairs (a0, a1), (a2, a3)
    g = w.reshape(N_OUT, N_IN // 4, 4)
    stored = np.stack([g[:, :, 0], g[:, :, 2], g[:, :, 1], g[:, :, 3]], axis=2).reshape(-1)
    GEN.mkdir(parents=True, exist_ok=True)
    lines = ['// Generated by harness/bench_stream.py gen. Do not edit.', '#pragma once', '#include <stdint.h>', '',
             f'#define S_IN {N_IN}', f'#define S_OUT {N_OUT}', f'#define S_CHK {chk}u', '',
             '// input (int16, 0..127)',
             'static const int16_t s_act[S_IN] __attribute__((aligned(4))) = {']
    lines += ['    ' + ', '.join(str(int(v)) for v in a[i:i + 32]) + ',' for i in range(0, N_IN, 32)]
    lines += ['};', '',
              '// weights, int8, row-major, each group of 4 stored as w0 w2 w1 w3; const, so they stay in flash',
              'static const int8_t s_w[S_OUT * S_IN] __attribute__((aligned(4))) = {']
    lines += ['    ' + ', '.join(str(int(v)) for v in stored[i:i + 32]) + ',' for i in range(0, stored.size, 32)]
    lines += ['};', '']
    (GEN / 'stream_data.h').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'wrote {GEN.relative_to(ROOT)}/stream_data.h: {N_OUT}x{N_IN} int8 ({stored.size // 1024} KB), checksum {chk}')


def run(args):
    import serial
    ser = serial.Serial(args.port, 115200, timeout=60)
    time.sleep(0.5)
    ser.reset_input_buffer()
    ser.write(b'?')
    info = ser.readline().decode().strip()
    print('board:', info)
    build = dict(kv.split('=', 1) for kv in info.split()[1:] if '=' in kv).get('build', '?')
    ser.write(b'B')
    rows = []
    while True:
        line = ser.readline().decode().strip()
        if not line:
            sys.exit('timeout waiting for the benchmark')
        if line == 'END':
            break
        if not line.startswith('B '):
            print('  ' + line)
            continue
        _, variant, cmin, cmean, chk, ok = line.split()
        rows.append(dict(variant=variant, cycles_min=int(cmin), cycles_mean=int(cmean), ok=ok == '1'))
        print(f'  {variant:14s} cycles min {int(cmin):>8}  mean {int(cmean):>8}  '
              f'{"bit-exact" if ok == "1" else "MISMATCH chk " + chk}')
    if not all(r['ok'] for r in rows):
        print('ERROR: some variant output differs from the expected checksum')
    if args.csv and rows:
        new = not Path(args.csv).exists()
        with open(args.csv, 'a', newline='', encoding='utf-8') as f:
            wr = csv.writer(f)
            if new:
                wr.writerow(['date', 'build', 'variant', 'cycles_min', 'cycles_mean', 'ms_at_150mhz', 'bit_exact', 'notes'])
            now = datetime.datetime.now().strftime('%Y-%m-%d %H:%M')
            for r in rows:
                wr.writerow([now, build, r['variant'], r['cycles_min'], r['cycles_mean'],
                             f'{r["cycles_min"] / 150e3:.3f}', int(r['ok']), args.notes])
        print(f'  logged to {args.csv}')


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest='cmd', required=True)
    sub.add_parser('gen')
    r = sub.add_parser('run')
    r.add_argument('--port', default='COM3')
    r.add_argument('--csv', default=str(ROOT / 'results' / 'bench_stream.csv'))
    r.add_argument('--notes', default='')
    args = ap.parse_args()
    gen() if args.cmd == 'gen' else run(args)


if __name__ == '__main__':
    main()
