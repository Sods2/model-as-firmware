"""Export a trained model to the CMSIS-NN int8 baseline (Phase 0 step 5).

Weights: the exact integer codes of the BitNetMCU export (ternary, 4-bit, 8-bit), all of which fit int8.
Activations: int8, zero point 0, ReLU fused as a clamp to 0..127. Each layer gets one static
requantization scale, calibrated as max(accumulator) over MNIST *training* images (TFLite-style
min/max calibration), so the test set is never seen.

Because the network has no biases and only ReLU/max-pool non-linearities, it is positively homogeneous:
static scales instead of BitNetMCU's per-image shifts change the arithmetic, not the network.

Writes firmware/baselines/cmsis_nn/model_s8_<model>.h; harness/golden.py:GoldenS8 reads it back.

Usage: python harness/export_cmsis.py --model tern80
"""
import argparse
import math
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from golden import Golden, GoldenS8, conv3x3_valid, pool2, requant_single_rounding  # noqa: E402
from run import ROOT, load_mnist  # noqa: E402

OUT_DIR = ROOT / 'firmware' / 'baselines' / 'cmsis_nn'


def quantize_multiplier(real):
    """TFLite QuantizeMultiplier: real = mult * 2^(shift - 31), mult in [2^30, 2^31)."""
    q, shift = math.frexp(real)
    mult = int(round(q * (1 << 31)))
    if mult == 1 << 31:
        mult //= 2
        shift += 1
    assert -31 < shift <= 30
    return mult, shift


def calibrate(g, imgs):
    """Run the int8 network layer by layer, choosing each layer's scale from the calibration maxima."""
    q = {}

    def step(acc, layer, signed=False):
        top = np.abs(acc).max() if signed else acc.max()
        q[layer] = quantize_multiplier(127.0 / float(top))
        lo = -128 if signed else 0
        return requant_single_rounding(acc, *q[layer], lo, 127)

    x = imgs.astype(np.int64).reshape(-1, 1, 16, 16)
    x = step(conv3x3_valid(x, g.k1), 'CONV1')
    x = step(conv3x3_valid(x, g.k2), 'DW1')
    x = pool2(x)
    x = step(conv3x3_valid(x, g.k3), 'DW2')
    x = pool2(x).reshape(x.shape[0], -1)
    x = step(x @ g.fc1.T, 'FC1')
    x = step(x @ g.fc2.T, 'FC2')
    step(x @ g.fc3.T, 'FC3', signed=True)
    return q


def c_array(ctype, name, vals, per_line=16):
    vals = [int(v) for v in np.asarray(vals).ravel()]
    lines = [', '.join(str(v) for v in vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return f'const {ctype} {name}[] = {{\n    ' + ',\n    '.join(lines) + '\n};\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--model', default='tern80')
    ap.add_argument('--calib', type=int, default=10000, help='number of MNIST training images for calibration')
    args = ap.parse_args()

    g = Golden(ROOT / 'train' / 'export' / f'{args.model}.h')
    _, _, calib = load_mnist(args.calib, train=True)
    q = calibrate(g, calib)
    c = g.n_ch

    # CMSIS-NN layouts (NHWC activations)
    conv1_w = g.k1.reshape(c, 3, 3, 1)                      # OHWI
    dw1_w = g.k2.transpose(1, 2, 0)                          # [1,] H W C
    dw2_w = g.k3.transpose(1, 2, 0)
    nhwc_cols = [ch * 4 + p for p in range(4) for ch in range(c)]   # nhwc position -> nchw column
    fc1_w = g.fc1[:, nhwc_cols]
    for w in (conv1_w, dw1_w, dw2_w, fc1_w, g.fc2, g.fc3):
        assert w.min() >= -128 and w.max() <= 127

    out = OUT_DIR / f'model_s8_{args.model}.h'
    with open(out, 'w', newline='\n') as f:
        f.write(f'// CMSIS-NN int8 export of train/export/{args.model}.h, generated by harness/export_cmsis.py\n')
        f.write(f'// Calibration: max accumulator over the first {args.calib} MNIST training images.\n')
        f.write('#include <stdint.h>\n\n#ifndef MODEL_S8_H\n#define MODEL_S8_H\n\n')
        f.write(f'#define S8_CH {c}\n')
        f.write(f'#define S8_FC1_OUT {g.fc1.shape[0]}\n#define S8_FC2_OUT {g.fc2.shape[0]}\n#define S8_FC3_OUT {g.fc3.shape[0]}\n')
        for layer, (m, s) in q.items():
            f.write(f'#define S8_{layer}_MULT {m}\n#define S8_{layer}_SHIFT {s}\n')
        f.write('\n')
        f.write(c_array('int8_t', 's8_conv1_w', conv1_w))
        f.write(c_array('int8_t', 's8_dw1_w', dw1_w))
        f.write(c_array('int8_t', 's8_dw2_w', dw2_w))
        f.write(c_array('int8_t', 's8_fc1_w', fc1_w))
        f.write(c_array('int8_t', 's8_fc2_w', g.fc2))
        f.write(c_array('int8_t', 's8_fc3_w', g.fc3))
        f.write('\n#endif\n')

    # round-trip check: the golden model read back from the header must reproduce the calibration pass
    gs = GoldenS8(out)
    assert gs.q == q
    print(f'wrote {out.relative_to(ROOT)}')
    for layer, (m, s) in q.items():
        print(f'  {layer:5s} mult {m} shift {s}  (scale {m * 2.0 ** (s - 31):.6g})')


if __name__ == '__main__':
    main()
