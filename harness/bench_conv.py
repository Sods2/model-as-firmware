"""Wide-conv fairness benchmark (FINDINGS F5/F17): one 3x3 conv layer with many input channels, the shape
CMSIS-NN's im2col + SMLAD path is built for, against mafc's method (ternary weights compiled into code).

  gen:  write firmware/bench/conv_wide/gen/{bench_data.h, bench_code.c}: input, ternary weights at several
        sparsities, the exact expected output checksums, and one generated "code" kernel per sparsity.
  run:  talk to the flashed benchmark firmware over USB serial, check every kernel's output checksum, and
        append one CSV row per (kernel, sparsity).

Layer: input 10x10x32 (NHWC, int8 in 0..127, i.e. after a ReLU), 32 filters 3x3x32 (ternary), valid conv,
output 8x8x32 int8. Requantization is the same for every kernel: out = clamp(round_half_up(sum / 2^sh), 0, 127),
which is exactly CMSIS-NN's requantize with multiplier 2^30 and shift 1 - sh (single rounding). So all kernels
must produce identical bytes.

  train/.venv/Scripts/python.exe harness/bench_conv.py gen
  (build + flash firmware/bench/conv_wide, RUN_FROM_RAM=ON/OFF)
  train/.venv/Scripts/python.exe harness/bench_conv.py run --port COM3 --csv results/bench_conv.csv
"""
import argparse
import csv
import datetime
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / 'firmware' / 'bench' / 'conv_wide' / 'gen'
H = W = 10
CIN = COUT = 32
OH, OW = H - 2, W - 2
ZERO_FRACS = (0.0, 0.33, 0.5, 0.7, 0.9)
SEED = 1234


def make_data():
    rng = np.random.default_rng(SEED)
    act = rng.integers(0, 128, size=(H, W, CIN), dtype=np.int64)
    weights = {}
    for z in ZERO_FRACS:
        w = rng.choice([-1, 1], size=(COUT, 3, 3, CIN))
        mask = rng.random((COUT, 3, 3, CIN)) < z
        w[mask] = 0
        weights[z] = w.astype(np.int64)
    return act, weights


def conv_sums(act, w):
    out = np.zeros((OH, OW, COUT), dtype=np.int64)
    for ky in range(3):
        for kx in range(3):
            patch = act[ky:ky + OH, kx:kx + OW, :]                    # (OH, OW, CIN)
            out += np.einsum('yxc,oc->yxo', patch, w[:, ky, kx, :])
    return out


def pick_shift(s):
    """Smallest shift that keeps the 99th percentile of the positive sums within 127."""
    pos = s[s > 0]
    top = np.percentile(pos, 99) if pos.size else 1
    sh = 1
    while top / (1 << sh) > 127:
        sh += 1
    return sh


def requant(s, sh):
    # CMSIS-NN single rounding, multiplier 2^30, shift 1 - sh: ((s * 2^30) >> (30 - (1 - sh)) + 1) >> 1
    v = ((s << 30) >> (29 + sh)) + 1 >> 1
    return np.clip(v, 0, 127)


def checksum(out_bytes):
    o = np.asarray(out_bytes, dtype=np.int64).reshape(-1)
    k = (np.arange(o.size) % 251) + 1
    return int((o * k).sum() & 0xFFFFFFFF)


def c_array(ctype, name, vals, per_line=32):
    vals = [int(v) for v in np.asarray(vals).reshape(-1)]
    rows = [', '.join(str(v) for v in vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return f'static const {ctype} {name}[{len(vals)}] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'


def tag(z):
    return f's{int(round(z * 100))}'


def gen():
    act, weights = make_data()
    GEN.mkdir(parents=True, exist_ok=True)
    data = ['// Generated by harness/bench_conv.py gen. Do not edit.', '#pragma once', '#include <stdint.h>', '',
            f'#define BH {H}', f'#define BW {W}', f'#define BCIN {CIN}', f'#define BCOUT {COUT}',
            f'#define BOH {OH}', f'#define BOW {OW}', f'#define BN_SPARSITY {len(ZERO_FRACS)}', '',
            '// input, NHWC int8 (0..127)', c_array('int8_t', 'b_act', act)]
    code = ['// Generated by harness/bench_conv.py gen. Do not edit.',
            '// mafc method on a wide conv: ternary weights compiled into code, one straight-line sum per output',
            '// channel, inside a loop over output pixels. Input NHWC int8, output NHWC int8.',
            '#include <stdint.h>', '#include "bench_kernels.h"', '']
    table = []
    for z in ZERO_FRACS:
        w = weights[z]
        s = conv_sums(act, w)
        sh = pick_shift(s)
        ref = requant(s, sh)
        chk = checksum(ref)
        nnz = int(np.count_nonzero(w))
        t = tag(z)
        data += [f'// zero fraction {z}: {nnz} nonzero weights, shift {sh}, expected output checksum',
                 c_array('int8_t', f'b_w_{t}', w),   # OHWI, as CMSIS-NN wants
                 f'#define B_SHIFT_{t.upper()} {sh}', f'#define B_CHK_{t.upper()} {chk}u', '']
        rnd = 1 << (sh - 1)
        lines = [f'// zero fraction {z}: {nnz} nonzeros ({nnz // COUT} per output channel on average), shift {sh}',
                 f'BENCH_IN_SRAM void conv_code_{t}(const int8_t *restrict in, int8_t *restrict out) {{',
                 f'    for (int oy = 0; oy < {OH}; oy++) {{',
                 f'        for (int ox = 0; ox < {OW}; ox++) {{',
                 f'            const int8_t *p = in + (oy * {W} + ox) * {CIN};',
                 f'            int8_t *o = out + (oy * {OW} + ox) * {COUT};',
                 '            int32_t s;']
        for oc in range(COUT):
            terms = []
            for ky in range(3):
                for kx in range(3):
                    for ci in range(CIN):
                        v = w[oc, ky, kx, ci]
                        if v:
                            terms.append(('+ ' if v > 0 else '- ') + f'p[{(ky * W + kx) * CIN + ci}]')
            expr = ' '.join(terms).lstrip('+ ') if terms else '0'
            text, line = [], ''
            for tok in expr.split(' '):
                if len(line) + len(tok) > 100:
                    text.append(line)
                    line = ''
                line += (' ' if line else '') + tok
            text.append(line)
            lines.append('            s = ' + ('\n                ').join(text) + ';')
            lines.append(f'            o[{oc}] = (int8_t)BENCH_USAT((s + {rnd}) >> {sh}, 7);')
        lines += ['        }', '    }', '}', '']
        code += lines
        table.append((t, sh, chk, nnz))
    data += ['// per sparsity: weights, shift, expected checksum, nonzeros',
             'typedef struct { const char *name; const int8_t *w; int shift; uint32_t chk; int nnz; '
             'void (*code)(const int8_t *, int8_t *); } bench_case_t;',
             '#include "bench_kernels.h"'] +             [f'void conv_code_{t}(const int8_t *restrict in, int8_t *restrict out);' for t, *_ in table] + [
             'static const bench_case_t b_cases[BN_SPARSITY] = {'] + \
            [f'    {{"{t}", b_w_{t}, {sh}, {chk}u, {nnz}, conv_code_{t}}},' for t, sh, chk, nnz in table] + ['};', '']
    (GEN / 'bench_data.h').write_text('\n'.join(data), encoding='utf-8', newline='\n')
    (GEN / 'bench_code.c').write_text('\n'.join(code), encoding='utf-8', newline='\n')
    for t, sh, chk, nnz in table:
        print(f'{t}: {nnz} nonzeros, shift {sh}, checksum {chk}')
    print(f'wrote {GEN.relative_to(ROOT)}/bench_data.h, bench_code.c')


def run(args):
    import serial
    ser = serial.Serial(args.port, 115200, timeout=60)
    time.sleep(0.5)
    ser.reset_input_buffer()
    ser.write(b'?')
    info = ser.readline().decode().strip()
    print('board:', info)
    build = dict(kv.split('=', 1) for kv in info.split()[1:] if '=' in kv).get('build', '?')
    ser.write(b'B')
    rows = []
    while True:
        line = ser.readline().decode().strip()
        if not line:
            sys.exit('timeout waiting for the benchmark')
        if line == 'END':
            break
        if not line.startswith('B '):
            print('  ' + line)
            continue
        _, kernel, case, nnz, cmin, cmean, chk, ok = line.split()
        rows.append(dict(kernel=kernel, case=case, nnz=int(nnz), cycles_min=int(cmin), cycles_mean=int(cmean),
                         ok=ok == '1'))
        print(f'  {kernel:12s} {case}  nnz {nnz:>5}  cycles min {int(cmin):>8}  mean {int(cmean):>8}  '
              f'{"bit-exact" if ok == "1" else "MISMATCH chk " + chk}')
    if not all(r['ok'] for r in rows):
        print('ERROR: some kernel output differs from the expected checksum')
    if args.csv and rows:
        new = not Path(args.csv).exists()
        with open(args.csv, 'a', newline='', encoding='utf-8') as f:
            wr = csv.writer(f)
            if new:
                wr.writerow(['date', 'build', 'kernel', 'case', 'nnz', 'cycles_min', 'cycles_mean', 'ms_at_150mhz',
                             'bit_exact', 'notes'])
            now = datetime.datetime.now().strftime('%Y-%m-%d %H:%M')
            for r in rows:
                wr.writerow([now, build, r['kernel'], r['case'], r['nnz'], r['cycles_min'], r['cycles_mean'],
                             f'{r["cycles_min"] / 150e3:.3f}', int(r['ok']), args.notes])
        print(f'  logged to {args.csv}')


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest='cmd', required=True)
    sub.add_parser('gen')
    r = sub.add_parser('run')
    r.add_argument('--port', default='COM3')
    r.add_argument('--csv', default=str(ROOT / 'results' / 'bench_conv.csv'))
    r.add_argument('--notes', default='')
    args = ap.parse_args()
    gen() if args.cmd == 'gen' else run(args)


if __name__ == '__main__':
    main()
